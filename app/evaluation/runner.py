"""Automated benchmark evaluation runner and summary report generator."""

from __future__ import annotations

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from app.evaluation.dataset import BenchmarkDataset, EvaluationSample
from app.evaluation.metrics import EvaluationScorecard, evaluate_research_sample
from app.evaluation.tracer import ExecutionTracer
from app.graph.workflow import ResearchOrchestrator
from app.retrieval.evidence import EvidenceManager
from app.retrieval.ingestion import DocumentIngestor
from app.retrieval.models import Document
from app.retrieval.vector_store import VectorStore


class SampleEvaluationResult(BaseModel):
    """Evaluation result for an individual benchmark sample."""

    sample_id: str
    query: str
    scorecard: EvaluationScorecard
    duration_ms: float
    report_snippet: str


class BenchmarkRunReport(BaseModel):
    """Aggregate benchmark evaluation report."""

    dataset_name: str
    total_samples: int
    avg_composite_score: float
    avg_context_precision: float
    avg_context_recall: float
    avg_faithfulness: float
    avg_citation_accuracy: float
    avg_latency_ms: float
    sample_results: List[SampleEvaluationResult] = Field(default_factory=list)

    def to_markdown(self) -> str:
        """Format the benchmark report as a clean markdown scorecard table."""
        rows = []
        for res in self.sample_results:
            sc = res.scorecard
            rows.append(
                f"| `{res.sample_id}` | {sc.composite_score:.2f} | {sc.context_precision:.2f} | "
                f"{sc.context_recall:.2f} | {sc.faithfulness_score:.2f} | {sc.citation_accuracy:.2f} | "
                f"{res.duration_ms:.1f}ms |"
            )

        table_body = "\n".join(rows)

        return f"""# 📊 Benchmark Evaluation Report: {self.dataset_name}

## Summary Overview
* **Total Samples**: {self.total_samples}
* **Mean Composite Score**: **{self.avg_composite_score:.4f} / 1.00**
* **Context Precision**: **{self.avg_context_precision:.4f}**
* **Context Recall**: **{self.avg_context_recall:.4f}**
* **Factual Faithfulness**: **{self.avg_faithfulness:.4f}**
* **Citation Accuracy**: **{self.avg_citation_accuracy:.4f}**
* **Average Latency**: **{self.avg_latency_ms:.1f} ms**

## Detailed Sample Scorecard
| Sample ID | Composite | Precision | Recall | Faithfulness | Citations | Latency |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- |
{table_body}

---
*Report generated by Agentic Research Intelligence Evaluation Engine.*
"""


class EvaluationRunner:
    """Executes systematic benchmarks against the multi-agent research platform."""

    def __init__(
        self,
        vector_store: Optional[VectorStore] = None,
        evidence_manager: Optional[EvidenceManager] = None,
    ):
        self.vector_store = vector_store or VectorStore()
        self.evidence_manager = evidence_manager or EvidenceManager(vector_store=self.vector_store)
        self._seed_default_sources()

    def _seed_default_sources(self):
        """Seed standard reference documents for benchmark evaluation."""
        default_docs = [
            Document(
                id="doc-001",
                title="Introduction to Retrieval-Augmented Generation",
                content="RAG combines retrieval with language generation to provide models with external context. Grounding with citations reduces error rates and hallucinations.",
            ),
            Document(
                id="doc-002",
                title="Agentic AI Systems",
                content="Agentic AI systems use models to plan tasks, select tools, execute actions, and adapt to results.",
            ),
            Document(
                id="doc-003",
                title="AI Evaluation",
                content="Evaluation measures the quality, reliability, and performance of AI systems.",
            ),
        ]
        ingestor = DocumentIngestor()
        for d in default_docs:
            chunks = ingestor.ingest_document(d)
            self.vector_store.add_documents([d], chunks)

    def run_benchmark(
        self,
        dataset: Optional[BenchmarkDataset] = None,
    ) -> BenchmarkRunReport:
        """Run all evaluation samples in dataset and return summary scorecard."""
        bench = dataset or BenchmarkDataset.get_default_benchmarks()
        orchestrator = ResearchOrchestrator(
            vector_store=self.vector_store,
            evidence_manager=self.evidence_manager,
        )

        sample_results: List[SampleEvaluationResult] = []

        for sample in bench.samples:
            tracer = ExecutionTracer()
            span = tracer.start_span("orchestrator_run", "ResearchOrchestrator", {"query": sample.query})

            final_state = orchestrator.run(sample.query)

            tracer.end_span(span.span_id, {"status": "completed"})

            scorecard = evaluate_research_sample(
                query=sample.query,
                retrieved_results=final_state.search_results,
                claims=final_state.extracted_claims,
                evidence_items=final_state.verified_evidence,
                final_report=final_state.final_report or "",
                expected_source_ids=sample.expected_source_ids,
            )

            sample_results.append(
                SampleEvaluationResult(
                    sample_id=sample.id,
                    query=sample.query,
                    scorecard=scorecard,
                    duration_ms=tracer.get_total_duration_ms(),
                    report_snippet=(final_state.final_report or "")[:150],
                )
            )

        n = len(sample_results) or 1
        avg_comp = sum(r.scorecard.composite_score for r in sample_results) / n
        avg_prec = sum(r.scorecard.context_precision for r in sample_results) / n
        avg_rec = sum(r.scorecard.context_recall for r in sample_results) / n
        avg_faith = sum(r.scorecard.faithfulness_score for r in sample_results) / n
        avg_cite = sum(r.scorecard.citation_accuracy for r in sample_results) / n
        avg_lat = sum(r.duration_ms for r in sample_results) / n

        return BenchmarkRunReport(
            dataset_name=bench.name,
            total_samples=len(sample_results),
            avg_composite_score=round(avg_comp, 4),
            avg_context_precision=round(avg_prec, 4),
            avg_context_recall=round(avg_rec, 4),
            avg_faithfulness=round(avg_faith, 4),
            avg_citation_accuracy=round(avg_cite, 4),
            avg_latency_ms=round(avg_lat, 2),
            sample_results=sample_results,
        )
